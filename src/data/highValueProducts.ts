// Generate final populated catalog with computed deposit and formatted price strings
export function generateCatalog(): HighValueProduct[] {
  return RAW_CATALOG.map((item) => {
    const formatted = formatBDT(item.priceBDT);
    // Booking deposit: 10% for phones/electronics, 5% for mega vehicles/assets, minimum ৳50 or up to price
    const depositPct = item.priceBDT > 5000000 ? 0.05 : 0.10;
    const calcDeposit = Math.round(item.priceBDT * depositPct);
    const bookingDepositBDT = item.priceBDT < 1000 
      ? Math.min(item.priceBDT, Math.max(50, calcDeposit))
      : Math.max(500, calcDeposit);
    const agentCommissionBDT = Math.round((item.priceBDT * item.agentCommissionRate) / 100);

    const discountPercent = item.discountPercent || (
      item.originalPriceBDT && item.originalPriceBDT > item.priceBDT
        ? Math.round(((item.originalPriceBDT - item.priceBDT) / item.originalPriceBDT) * 100)
        : undefined
    );

    return {
      ...item,
      discountPercent,
      priceFormattedBn: formatted.bn,
      priceFormattedEn: formatted.en,
      bookingDepositBDT,
      agentCommissionBDT,
    };
  });
}

export const CATALOG_STORAGE_KEY = 'uwallet_custom_catalog_v1';

// Static export guaranteed with ZERO repetitions and authentic Bangladesh market pricing
export const HIGH_VALUE_CATALOG: HighValueProduct[] = generateCatalog();

export function loadCatalog(): HighValueProduct[] {
  try {
    const raw = localStorage.getItem(CATALOG_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // If stored catalog is missing newly added featured items like EWG-DRZ-T9-TRIMMER, prepend it!
        const hasT9 = parsed.some((p: any) => p.id === 'EWG-DRZ-T9-TRIMMER');
        if (!hasT9) {
          const fresh = generateCatalog();
          const t9Item = fresh.find(p => p.id === 'EWG-DRZ-T9-TRIMMER');
          if (t9Item) {
            const merged = [t9Item, ...parsed];
            localStorage.setItem(CATALOG_STORAGE_KEY, JSON.stringify(merged));
            return merged;
          }
        }
        return parsed;
      }
    }
  } catch (e) {
    console.error('Error loading custom catalog:', e);
  }
  return generateCatalog();
}

export function saveCatalog(items: HighValueProduct[]): void {
  try {
    localStorage.setItem(CATALOG_STORAGE_KEY, JSON.stringify(items));
    window.dispatchEvent(new CustomEvent('uwallet_catalog_updated', { detail: items }));
  } catch (e) {
    console.error('Error saving catalog:', e);
  }
}

export function resetCatalogToDefault(): HighValueProduct[] {
  try {
    localStorage.removeItem(CATALOG_STORAGE_KEY);
    const defaults = generateCatalog();
    window.dispatchEvent(new CustomEvent('uwallet_catalog_updated', { detail: defaults }));
    return defaults;
  } catch (e) {
    console.error(e);
    return generateCatalog();
  }
}

