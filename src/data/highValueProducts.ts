export function formatBDT(amount: number): { bn: string; en: string } {
  if (amount >= 10000000) {
    const crore = amount / 10000000;
    const formatted = crore.toFixed(crore >= 10 ? 1 : 2).replace(/\.00$/, '');
    return {
      bn: `৳${formatted} কোটি`,
      en: `৳${formatted} Crore`,
    };
  } else if (amount >= 100000) {
    const lakh = amount / 100000;
    const formatted = lakh.toFixed(lakh >= 10 ? 1 : 2).replace(/\.00$/, '');
    return {
      bn: `৳${formatted} লাখ`,
      en: `৳${formatted} Lakh`,
    };
  } else {
    return {
      bn: `৳${amount.toLocaleString('en-IN')}`,
      en: `৳${amount.toLocaleString('en-US')}`,
    };
  }
}

